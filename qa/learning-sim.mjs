// Writes qa/learning-sim.md: proof that the engine adapts to a kid who always misses the 7s.
// Run via: npx vite-node qa/learning-sim.mjs  (or npm run sim)
import fs from 'node:fs';
import { PROFILES, mean, simulate } from '../src/logic/sim.ts';

const rounds = 60;
const seeds = [1, 2, 3, 4, 5];
const rows = [];
for (const profile of [PROFILES.solid, PROFILES.missesSevens]) {
  const reps = seeds.map((s) => simulate(profile, rounds, s));
  const early = mean(reps.map((r) => mean(r.sevenShare, 0, 10)));
  const late = mean(reps.map((r) => mean(r.sevenShare, r.sevenShare.length - 20)));
  const rules7 = mean(reps.map((r) => r.focusSevenRules / Math.max(1, r.totalRules)));
  rows.push({ name: profile.name, early, late, rules7, runs: mean(reps.map((r) => r.runs)) });
}
const pct = (x) => `${(x * 100).toFixed(1)}%`;
const md = `# Learning-engine proof (simulated players)

Generated by \`qa/learning-sim.mjs\` on ${new Date().toISOString().slice(0, 10)} — ${rounds} rounds × ${seeds.length} seeds per profile, all tables unlocked.
"7-share" = share of *correct targets the engine served* (grid blocks + boss facts) that involve the 7 table.
Neutral exposure would be about 11/66 ≈ 16.7%.

| Profile | 7-share, first 10 rounds | 7-share, last 20 rounds | "MULTIPLES OF 7" rules | runs needed |
|---|---|---|---|---|
${rows.map((r) => `| ${r.name} | ${pct(r.early)} | ${pct(r.late)} | ${pct(r.rules7)} | ${r.runs.toFixed(1)} |`).join('\n')}

**Result:** the kid who always misses the 7s is served ${(rows[1].late / rows[0].late).toFixed(1)}× more 7-facts late in play than a solid player,
while assist shimmer + heat-scaled focus keep the rounds survivable. The same assertions run in CI (\`tests/learning.test.ts\`).
`;
fs.writeFileSync('qa/learning-sim.md', md);
console.log(md);
